<?php

namespace App\Filament\Resources\Purchases\Pages;

use App\Enums\PurchaseStatus;
use App\Filament\Resources\Purchases\Actions\ConfirmPurchaseAction;
use App\Filament\Resources\Purchases\Pages\Concerns\HandlesPurchaseFormData;
use App\Filament\Resources\Purchases\PurchaseResource;
use App\Models\Purchase;
use Filament\Resources\Pages\CreateRecord;

class CreatePurchase extends CreateRecord
{
    use HandlesPurchaseFormData;

    protected static string $resource = PurchaseResource::class;

    protected function mutateFormDataBeforeCreate(array $data): array
    {
        $data = $this->preparePurchaseData($data);

        // purchase_number is generated by GeneratesDocumentCode
        $data['status'] = PurchaseStatus::DRAFT->value;
        $data['user_id'] = auth()->id();

        return $data;
    }

    protected function afterCreate(): void
    {
        /** @var Purchase $record */
        $record = $this->record;

        $this->syncPurchaseTotals($record);

        // Purchases are confirmed on save; the paid amount becomes the first payment
        ConfirmPurchaseAction::confirm($record);
    }
}
